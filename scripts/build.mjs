// Build dist/pip-engine.mjs: engine sources embedded as strings + frameDoc. No dependencies.
// Usage: node scripts/build.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = p => readFileSync(join(root, p), 'utf8');
const pkg = JSON.parse(read('package.json'));
const frame = read('src/frame.mjs');
const out = `/* pip-engine ${pkg.version} · MIT · https://github.com/GreatPyreneseDad/pip-engine
   Generated by scripts/build.mjs. Do not edit; edit src/ and rebuild. */
export const VERSION = ${JSON.stringify(pkg.version)};
export const LIB = ${JSON.stringify(read('src/lib.js'))};
export const RUNTIME = ${JSON.stringify(read('src/runtime.js'))};
export const LOOP = ${JSON.stringify(read('src/loop.js'))};
export const CONTRACT = ${JSON.stringify(read('api/kit.md'))};
${frame}
export const engine = { lib: LIB, runtime: RUNTIME, loop: LOOP };
`;
mkdirSync(join(root, 'dist'), { recursive: true });
writeFileSync(join(root, 'dist/pip-engine.mjs'), out);
console.log(`dist/pip-engine.mjs  ${out.length} bytes  v${pkg.version}`);
